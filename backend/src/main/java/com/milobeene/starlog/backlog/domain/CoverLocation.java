package com.milobeene.starlog.backlog.domain;

/**
 * 커버 파일이 어디 있는가 (v1.0 6단계, architecture §4).
 *
 * ## 왜 커버 한 장 한 장이 들고 있나
 *
 * 앱 전체 설정으로 두면 **설정을 바꾸는 순간 이미 있는 커버가 전부 깨진다.**
 * "스토리지를 쓰다가 껐다"거나 "로컬로 쓰다 클라우드를 붙였다"가 실제로 일어나는 일이고,
 * 그때 옛 커버는 여전히 옛 자리에 있다. 위치를 파일마다 들고 있으면
 * **섞여 있어도 각자 제자리에서 읽힌다.**
 *
 * 그래서 나중에 "전부 옮기기"도 가능해진다 — 한 장씩 옮기고 값을 바꾸면 되니까.
 */
public enum CoverLocation {

    /** 데이터 루트의 `covers/` 폴더. 백엔드가 직접 읽고 쓴다 */
    LOCAL,

    /** S3 호환 스토리지. 브라우저가 프리사인드 URL로 직접 올린다 */
    EXTERNAL
}
