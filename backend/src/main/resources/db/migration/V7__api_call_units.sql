-- 호출 한 줄이 "얼마나 썼는지" (v1.0, 2026-08-28).
--
-- ## 왜 필요해졌나
--
-- 지금까지 사용량은 **호출 횟수**로만 셌다. IGDB는 그게 맞다 — 한도가 "초당 4회"처럼
-- 횟수로 매겨져 있다.
--
-- **번역은 다르다. 글자 수로 값이 매겨지고, 넘으면 돈이 나간다.**
-- 그래서 호출 한 줄에 "이번에 몇 자를 보냈나"를 함께 남겨야 이번 달 합계를 셀 수 있다.
--
-- ## null을 허용한다
--
-- IGDB·스토리지는 셀 단위가 없다. 0을 넣으면 "0자를 썼다"로 읽혀 합계가 거짓말이 되고,
-- 1을 넣으면 횟수와 뒤섞인다. **"이 줄에는 셀 단위가 없다"는 뜻은 null뿐이다.**
--
-- 옛 행도 전부 null이 된다 — 번역을 쓰기 전의 기록이라 그게 사실과 맞는다.
alter table api_call_log add column units bigint;

-- 이번 달 합계를 자주 묻는다 (한 번 번역할 때마다). 제공자별 기간 조회라 이 순서다
create index idx_api_call_log_provider_called_at on api_call_log (provider, called_at);
