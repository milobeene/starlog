-- V1: 초기 스키마 (O-1). Hibernate 스키마 생성(ddl-auto: create) 시절의 최종 형태를
-- PostgreSQL 방언으로 덤프한 뒤 손 감사한 결과다.
--
-- 덤프 대비 달라진 것:
--   * FK·check 제약에 이름 부여 (OI-16) — 해시 이름은 에러 메시지에서 읽을 수 없다
--   * cover_image의 unique에 이름 복원 — 엔티티에는 있었는데 Hibernate가 인라인으로 뭉갰다
--   * game.summary/storyline → text (OI-15) — varchar(32600)으로 나오던 것을 엔티티와 함께 교정
--   * FK 컬럼 인덱스 명시 — H2는 FK에 인덱스를 자동 생성하지만 PostgreSQL은 안 한다.
--     이미 유니크·인덱스의 선두 컬럼인 FK는 제외
--
-- H2(MODE=PostgreSQL)와 PostgreSQL 양쪽에서 도는 문법만 쓴다.

-- ============ 회원 ============

create table member (
    id              bigint generated by default as identity primary key,
    email           varchar(320) not null,
    nickname        varchar(30)  not null,
    password        varchar(100),
    google_subject  varchar(100),
    role            varchar(20)  not null,
    email_verified  boolean      not null,
    memo            text,
    deleted_at      timestamp(6),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint uk_member_email unique (email),
    constraint uk_member_google_subject unique (google_subject),
    constraint chk_member_role check (role in ('USER','ADMIN'))
);

create index idx_member_deleted_at on member (deleted_at);

create table auth_token (
    id          bigint generated by default as identity primary key,
    member_id   bigint       not null,
    purpose     varchar(30)  not null,
    token_hash  varchar(100) not null,
    expires_at  timestamp(6) not null,
    used_at     timestamp(6),
    created_at  timestamp(6),
    updated_at  timestamp(6),
    constraint uk_auth_token_hash unique (token_hash),
    constraint chk_auth_token_purpose check (purpose in ('EMAIL_VERIFICATION','PASSWORD_RESET')),
    constraint fk_auth_token_member foreign key (member_id) references member (id)
);

create index idx_auth_token_expires_at on auth_token (expires_at);
create index idx_auth_token_member on auth_token (member_id);

create table audit_log (
    id          bigint generated by default as identity primary key,
    actor_id    bigint      not null,
    action      varchar(50) not null,
    target_type varchar(50),
    target_id   bigint,
    request_ip  varchar(50),
    user_agent  varchar(500),
    created_at  timestamp(6),
    updated_at  timestamp(6),
    constraint fk_audit_log_actor foreign key (actor_id) references member (id)
);

create index idx_audit_log_actor on audit_log (actor_id);

