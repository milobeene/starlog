create table backlog_entry (
    id                           bigint generated by default as identity primary key,
    member_id                    bigint       not null,
    game_id                      bigint       not null,
    status                       varchar(20)  not null,
    display_name                 varchar(300) not null,
    name_override                varchar(300),
    released_on_override         date,
    released_on_resolved         date,
    list_price_override_amount   numeric(19,2),
    list_price_override_currency varchar(3),
    rating                       numeric(4,1),
    play_time_hours              integer,
    last_played_on               date,
    last_playthrough_id          bigint,
    memo                         text,
    deleted_at                   timestamp(6),
    created_at                   timestamp(6),
    updated_at                   timestamp(6),
    constraint uk_backlog_entry_member_game unique (member_id, game_id),
    constraint chk_backlog_entry_status check (status in ('WISHLIST','BACKLOG','PLAYING','PAUSED','DROPPED','COMPLETED')),
    constraint fk_backlog_entry_member foreign key (member_id) references member (id),
    constraint fk_backlog_entry_game foreign key (game_id) references game (id)
);

create index idx_backlog_member_status on backlog_entry (member_id, status);
create index idx_backlog_member_last_played on backlog_entry (member_id, last_played_on);
create index idx_backlog_member_display_name on backlog_entry (member_id, display_name);
create index idx_backlog_member_released_on on backlog_entry (member_id, released_on_resolved);
create index idx_backlog_entry_game on backlog_entry (game_id);
create index idx_backlog_entry_last_playthrough on backlog_entry (last_playthrough_id);

