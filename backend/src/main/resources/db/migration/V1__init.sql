-- V1: 스키마 베이스라인 (Phase 9 재작성, 2026-08-26).
--
-- 원래 V1(Hibernate 덤프 감사본) → V2(선택지 회원 소유 전환) → V3(가입 승인제)의
-- 3단 역사를 **하나로 청산한 판이다.** 첫 실배포 전 + 데이터가 소모품인 시점이라
-- 마이그레이션 역사를 유지할 이유가 없었다 — 새 환경마다 "member_device를 만들었다
-- 지우는" 가짜 역사를 재생하는 비용만 남는다. 옛 판은 git 이력에 있다.
--
-- 손으로 쓴 이유 — Hibernate 생성 DDL은 인덱스가 없고 제약 이름이 해시라
-- 에러 메시지에서 읽을 수 없다 (OI-16). 인덱스는 전부 실제 쿼리 경로가 근거다.
-- 근거 없는 인덱스는 두지 않았다 — 각 인덱스 옆 주석이 그 근거다.
--
-- FK 컬럼 인덱스 정책 — H2는 FK에 인덱스를 자동으로 만들지만 PostgreSQL은 안 만든다.
-- 조회·삭제 경로가 실재하는 FK만 명시적 인덱스를 건다. 유니크 제약의 선두 컬럼이면 생략
-- (유니크 인덱스의 접두어로 충분하다).
--
-- H2(MODE=PostgreSQL, dev)와 PostgreSQL(prod) 양쪽에서 도는 문법만 쓴다.
-- 부분 인덱스(where deleted_at is null)는 H2가 지원하지 않아 쓰지 않는다.

-- ============ 회원 ============

create table member (
    id              bigint generated by default as identity primary key,
    email           varchar(320) not null,
    nickname        varchar(30)  not null,
    password        varchar(100),                 -- null = 구글 전용 계정 (FR-AUTH-12)
    google_subject  varchar(100),
    role            varchar(20)  not null,
    email_verified  boolean      not null,
    approved_at     timestamp(6),                 -- null = 승인 대기 (FR-ADM-06)
    memo            text,
    deleted_at      timestamp(6),                 -- 탈퇴 유예 (FR-AUTH-09)
    created_at      timestamp(6),
    updated_at      timestamp(6),
    constraint uk_member_email unique (email),
    constraint uk_member_google_subject unique (google_subject),
    constraint chk_member_role check (role in ('USER','ADMIN'))
);

-- 유예 만료 물리 삭제 배치가 deleted_at < threshold로 훑는다 (FR-SYS-06)
create index idx_member_deleted_at on member (deleted_at);
-- approved_at 인덱스는 두지 않는다 — 승인제 자체가 회원 수를 강제로 작게 유지하고,
-- 대기 목록 조회는 전체 스캔으로 충분하다. 단독 필터 경로도 없다

create table auth_token (
    id          bigint generated by default as identity primary key,
    member_id   bigint       not null,
    purpose     varchar(30)  not null,
    token_hash  varchar(100) not null,
    expires_at  timestamp(6) not null,
    used_at     timestamp(6),                     -- null = 미사용
    created_at  timestamp(6),
    updated_at  timestamp(6),
    constraint uk_auth_token_hash unique (token_hash),
    constraint chk_auth_token_purpose check (purpose in ('EMAIL_VERIFICATION','PASSWORD_RESET')),
    constraint fk_auth_token_member foreign key (member_id) references member (id)
);

-- 정리 배치가 만료·사용분을 expires_at으로 지운다 (04:30 크론)
create index idx_auth_token_expires_at on auth_token (expires_at);
-- 회원 탈퇴 물리 삭제가 member_id로 지운다
create index idx_auth_token_member on auth_token (member_id);

create table audit_log (
    id          bigint generated by default as identity primary key,
    actor_id    bigint      not null,
    action      varchar(50) not null,
    target_type varchar(50),
    target_id   bigint,
    request_ip  varchar(50),
    user_agent  varchar(500),
    created_at  timestamp(6),
    updated_at  timestamp(6),
    constraint fk_audit_log_actor foreign key (actor_id) references member (id)
);

-- 회원 탈퇴 물리 삭제 경로
create index idx_audit_log_actor on audit_log (actor_id);
-- 보존 기간(1년, OI-08) 만료 삭제 배치가 created_at < threshold로 훑는다.
-- 옛 V1에 없던 인덱스다 — 로그는 단조 증가라 이 배치가 유일하게 전체를 훑는 경로였다
create index idx_audit_log_created_at on audit_log (created_at);

