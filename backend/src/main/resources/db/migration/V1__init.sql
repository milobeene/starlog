);

create index idx_acquisition_entry on acquisition (backlog_entry_id);
create index idx_acquisition_platform on acquisition (platform_id);
create index idx_acquisition_platform_account on acquisition (platform_account_id);
create index idx_acquisition_subscription on acquisition (subscription_id);

