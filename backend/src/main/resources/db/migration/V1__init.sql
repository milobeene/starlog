create table playthrough (
    id                  bigint generated by default as identity primary key,
    backlog_entry_id    bigint      not null,
    sequence_no         integer     not null,
    status              varchar(20) not null,
    label               varchar(100),
    started_on          date        not null,
    finished_on         date,                     -- null = 진행 중 (BR-PT-03의 판정 기준)
    platform_account_id bigint,
    device_id           bigint,
    emulator_id         bigint,
    input_method_id     bigint,
    created_at          timestamp(6),
    updated_at          timestamp(6),
    constraint uk_playthrough_sequence unique (backlog_entry_id, sequence_no),
    constraint chk_playthrough_status check (status in ('PLAYING','PAUSED','DROPPED','COMPLETED')),
    constraint fk_playthrough_entry foreign key (backlog_entry_id) references backlog_entry (id),
    constraint fk_playthrough_platform_account foreign key (platform_account_id) references platform_account (id),
    constraint fk_playthrough_device foreign key (device_id) references device (id),
    constraint fk_playthrough_emulator foreign key (emulator_id) references emulator (id),
    constraint fk_playthrough_input_method foreign key (input_method_id) references input_method (id)
);

-- 파셋 집계(기기별·계정별 항목 수)와 필터가 이 FK들로 그룹핑·조인한다 (H-4, FR-QRY-03)
create index idx_playthrough_platform_account on playthrough (platform_account_id);
create index idx_playthrough_device on playthrough (device_id);
create index idx_playthrough_emulator on playthrough (emulator_id);
create index idx_playthrough_input_method on playthrough (input_method_id);

-- backlog_entry.last_playthrough_id → playthrough는 상호 참조라 여기서 건다
alter table backlog_entry
    add constraint fk_backlog_entry_last_playthrough foreign key (last_playthrough_id) references playthrough (id);

