-- 태그 색상 (v1.2, 2026-08-29).
--
-- 사용자가 프리셋 팔레트에서 고른다. **자유 입력이 아니다** — 아무 색이나 받으면
-- 어두운 배경에서 안 읽히는 색이 섞이고, 화면마다 다른 톤이 나온다.
--
-- 저장하는 것은 **팔레트의 이름**(`rose`, `amber`…)이지 색값이 아니다.
-- 실제 색은 화면이 들고 있다 — 나중에 톤을 다듬어도 DB를 안 건드린다.
-- 그래서 varchar(16)이면 넉넉하다.
--
-- null은 "색 없음"이고 지금까지의 모양(중립 회색)을 그대로 쓴다.
-- 기존 태그에 색을 자동으로 뿌리지 않는다 — 사용자가 안 고른 것을 고른 것처럼 만들면 안 된다.
alter table tag add column color varchar(16);
