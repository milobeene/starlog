-- 플레이타임을 기록의 합으로 (v2 S4, 2026-10-25).
--
-- 지금까지 `backlog_entry.play_time_hours`는 손으로 덮어쓰는 숫자 하나였다. 이제 **기록이 원본**이고
-- 그 칸은 합계를 담아 두는 캐시다(정렬·카드·통계·대시보드가 읽는다). 합계는 STARLOG만 계산한다.
--
--   play_record       STARLOG가 쓰는 기록 — BASELINE(기존 기록) · ADJUST(직접 수정, 차이만) · ADD(추가)
--   homeops_play_log  homeops(일정 앱)가 쓸 자리. **STARLOG는 이 표에 쓰지 않는다** — 읽어서 합계에 더할 뿐이다.
--                     표를 나눈 이유: 한 표에 두면 어느 쪽이 남의 행을 고쳤는지 DB가 막아 줄 수 없다
--
-- 단위는 **분**(`numeric(8,1)`). 화면 입력은 정수 분인데, 실데이터에 2.38·1.62시간처럼 분으로 안 떨어지는
-- 합계가 있다. 시간 소수 둘째 자리(0.01시간 = 0.6분)는 분 소수 첫째 자리로 **정확히** 옮겨지므로
-- 기존 합계가 한 푼도 안 변하고, 정수 분 입력은 시간으로 반올림하지 않아 쌓여도 어긋나지 않는다.
-- 시간 칸으로는 `round(합/60, 2)`.
--
-- ⚠️ **실데이터(Neon)에서 처음 도는 파일이다.** 트랜잭션 하나(러너가 감싼다)라 중간에 멈추면 아무것도 안 바뀐다.
-- 맨 끝에서 "모든 항목의 합계가 그대로인가"를 다시 확인하고, 아니면 멈춘다.

create table play_record (
    id               bigint generated by default as identity primary key,
    backlog_entry_id bigint       not null,
    kind             varchar(20)  not null,
    -- 부호가 있다 — 직접 수정은 차이(4:30 → 4:00이면 -30)로 남긴다. "얼마로 바꿈"으로 남기면 다른 기록을 덮는다
    minutes          numeric(8,1) not null,
    played_on        date         not null,
    note             varchar(100),
    created_at       timestamp(6),
    updated_at       timestamp(6),
    constraint chk_play_record_kind check (kind in ('BASELINE','ADJUST','ADD')),
    constraint chk_play_record_add_positive check (kind <> 'ADD' or minutes > 0),
    constraint fk_play_record_entry foreign key (backlog_entry_id) references backlog_entry (id)
);

-- 항목별 목록(날짜 최신순)과 합계가 이 경로로 훑는다
create index idx_play_record_entry on play_record (backlog_entry_id, played_on);

-- homeops 일정 하나 = 한 행. 시각은 `timestamp`(KST 벽시계) — 우리 다른 시각 칸과 같다.
-- **끝난 일정만** 합계에 들어간다(`ended_at` ≤ 지금, 앱 시계). 앞으로 잡힌 일정은 보이기만 한다.
-- 항목을 완전 삭제하면 같이 사라진다(cascade) — 가리킬 게임이 없는 일정은 뜻이 없고,
-- STARLOG 코드가 이 표에 delete를 내지 않게 하려는 것이다
create table homeops_play_log (
    id               bigint generated by default as identity primary key,
    backlog_entry_id bigint       not null,
    -- homeops 쪽 일정 id. 다시 보내도 같은 행을 고치게(upsert) 유니크
    external_id      varchar(200) not null,
    started_at       timestamp(6) not null,
    ended_at         timestamp(6) not null,
    minutes          integer      not null,
    label            varchar(200),
    created_at       timestamp(6),
    updated_at       timestamp(6),
    constraint uk_homeops_play_log_external unique (external_id),
    constraint chk_homeops_play_log_minutes check (minutes >= 0),
    constraint chk_homeops_play_log_range check (ended_at >= started_at),
    constraint fk_homeops_play_log_entry foreign key (backlog_entry_id) references backlog_entry (id) on delete cascade
);

create index idx_homeops_play_log_entry on homeops_play_log (backlog_entry_id);

-- ── 기존 합계 → BASELINE 한 줄씩 ─────────────────────────────────────────
--
-- 합계가 있는 항목마다 하나(0시간도 — "0으로 적었음"과 "안 적음"은 다르다). 삭제된 항목도 —
-- 되살리면 시간이 그대로 돌아와야 한다. 날짜는 항목을 마지막으로 고친 날(없으면 담은 날):
-- 그 합계가 마지막으로 적힌 때에 가장 가깝다. 시각은 앱 시계를 못 쓰니(SQL 안이다) 기존 값을 그대로 옮긴다
insert into play_record (backlog_entry_id, kind, minutes, played_on, note, created_at, updated_at)
select id, 'BASELINE', play_time_hours * 60,
       coalesce(cast(updated_at as date), cast(created_at as date), date '2000-01-01'),
       null, updated_at, updated_at
  from backlog_entry
 where play_time_hours is not null
 order by id;

do $$
declare
  broken bigint;
begin
  select count(*) into broken
    from backlog_entry b
    left join (select backlog_entry_id, sum(minutes) m from play_record group by backlog_entry_id) r
           on r.backlog_entry_id = b.id
   where b.play_time_hours is distinct from round(r.m / 60, 2);
  if broken > 0 then
    raise exception 'V15 중단: 기록의 합이 기존 플레이타임과 다른 항목이 %개다', broken;
  end if;
end $$;
